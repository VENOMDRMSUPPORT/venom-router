#!/usr/bin/env node
// P2a-DS-005: locks the integration contract (handoff-contract.md, 07 §9/§10).
// @venom/design-system is FROZEN/read-only and consumed ONLY through its
// public `exports` map (mode 1, "file:../Design_System"). This script fails
// (non-zero exit, CI-blocking) if any of the following is true:
//
//   1. Dashboard source imports a package path that isn't in
//      Design_System/package.json's own `exports` map (e.g. reaching into
//      `@venom/design-system/dist/...` directly instead of a public subpath).
//   2. Dashboard source vendors a copy of a Design_System component/source
//      file (same filename as a real DS component, or contains the DS
//      token-build's own GENERATED header) instead of importing it.
//   3. Design_System/ has ANY uncommitted changes — the package is
//      read-only to the app; touching it here is a boundary breach.
//   4. Design_System/package.json's version has drifted from the version
//      this app was reviewed/pinned against (see PINNED_DS_VERSION below
//      and dashboard/CONSUMPTION.md) without a deliberate re-pin.
//
// No dependencies beyond Node's stdlib — this must run before `npm ci`.

import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Bump this alongside dashboard/CONSUMPTION.md's "Pinned version" section —
// never silently. See CONSUMPTION.md for the mode-1 rationale.
const PINNED_DS_VERSION = "1.0.0";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DASHBOARD_ROOT = path.resolve(__dirname, "..");
const REPO_ROOT = path.resolve(DASHBOARD_ROOT, "..");
const DS_ROOT = path.join(REPO_ROOT, "Design_System");
const SRC_ROOT = path.join(DASHBOARD_ROOT, "src");

const violations = [];

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

function escapeRegExp(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// --- Legal import subpaths, derived from Design_System's OWN exports map ---
// (never hand-duplicated — if the package's public surface changes, this
// check follows it automatically).
const dsPkg = JSON.parse(readFileSync(path.join(DS_ROOT, "package.json"), "utf8"));
const legalSubpaths = Object.keys(dsPkg.exports || {});

function isLegalImport(specifier) {
  const PKG = "@venom/design-system";
  if (specifier !== PKG && !specifier.startsWith(PKG + "/")) return true; // not this package
  const subpath = specifier === PKG ? "." : "." + specifier.slice(PKG.length);
  for (const pattern of legalSubpaths) {
    if (pattern === subpath) return true;
    if (pattern.includes("*")) {
      const re = new RegExp("^" + pattern.split("*").map(escapeRegExp).join(".*") + "$");
      if (re.test(subpath)) return true;
    }
  }
  return false;
}

const sourceFiles = walk(SRC_ROOT).filter((f) => /\.(ts|tsx|js|jsx|css)$/.test(f));

// A quoted string anywhere that names the package — covers `import ... from`,
// bare side-effect `import "..."`, `export * from`, and `require(...)`.
const SPECIFIER_RE = /["'](@venom\/design-system[^"']*)["']/g;

for (const file of sourceFiles) {
  const rel = path.relative(DASHBOARD_ROOT, file).replace(/\\/g, "/");
  const content = readFileSync(file, "utf8");

  let m;
  SPECIFIER_RE.lastIndex = 0;
  while ((m = SPECIFIER_RE.exec(content))) {
    const specifier = m[1];
    if (!isLegalImport(specifier)) {
      violations.push(
        `[internal-import] ${rel}: imports "${specifier}", which is not one of Design_System's public exports (${legalSubpaths.join(", ")})`,
      );
    }
  }
}

// --- Vendored DS component/source copies ---
const dsComponentFiles = walk(path.join(DS_ROOT, "components")).filter((f) => /\.(tsx|ts)$/.test(f));
const dsBasenames = new Set(dsComponentFiles.map((f) => path.basename(f)));
const GENERATED_HEADER = "GENERATED by validation/build-tokens.cjs";

for (const file of sourceFiles) {
  const rel = path.relative(DASHBOARD_ROOT, file).replace(/\\/g, "/");
  const base = path.basename(file);
  if (dsBasenames.has(base)) {
    violations.push(
      `[vendored-copy] ${rel}: filename matches a real Design_System component (components/**/${base}) — import it from the package instead of duplicating it`,
    );
  }
  const content = readFileSync(file, "utf8");
  if (content.includes(GENERATED_HEADER)) {
    violations.push(`[vendored-copy] ${rel}: contains Design_System's own "${GENERATED_HEADER}" header — a copied generated file, not an import`);
  }
}

// --- Design_System/ must be byte-clean: the package is read-only to the app ---
let gitStatus;
try {
  gitStatus = execFileSync("git", ["-C", REPO_ROOT, "status", "--porcelain", "Design_System/"], {
    encoding: "utf8",
  });
} catch (err) {
  console.error("check-ds-adherence: could not run `git status` on Design_System/:", err.message);
  process.exit(1);
}
if (gitStatus.trim().length > 0) {
  violations.push(`[package-edit] Design_System/ has uncommitted changes (must stay read-only):\n${gitStatus}`);
}

// --- Version pin ---
if (dsPkg.version !== PINNED_DS_VERSION) {
  violations.push(
    `[version-drift] Design_System/package.json version is "${dsPkg.version}", but the app is pinned/reviewed against "${PINNED_DS_VERSION}" (dashboard/scripts/check-ds-adherence.mjs + dashboard/CONSUMPTION.md) — update both deliberately, not silently, if this is an intended bump`,
  );
}

if (violations.length > 0) {
  console.error(`check-ds-adherence: FAILED — ${violations.length} violation(s)\n`);
  for (const v of violations) console.error(" - " + v);
  process.exit(1);
}

console.log(
  `check-ds-adherence: OK — pinned @venom/design-system@${PINNED_DS_VERSION}, ${sourceFiles.length} source files scanned, no internal imports, no vendored copies, Design_System/ untouched.`,
);
