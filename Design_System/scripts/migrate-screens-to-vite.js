#!/usr/bin/env node
// One-time codemod: converts ui_kits/venom-console/screens-*.jsx from the
// `window.VenomScreens.x = function Name({ V, React, go }) {...}` global-registry pattern
// (Babel-in-browser) into real ES module exports consumed by a Vite-compiled entry.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const DIR = path.join(ROOT, "ui_kits", "venom-console");
const FILES = ["screens-operate.jsx", "screens-insights.jsx", "screens-manage.jsx"];

const registry = []; // { id, name, file }

function migrateFile(filename) {
  const filePath = path.join(DIR, filename);
  const src = fs.readFileSync(filePath, "utf8");

  const re = /window\.VenomScreens(?:\.(\w+)|\["([\w-]+)"\])\s*=\s*function\s+(\w+)\(\{\s*([^}]*)\}\)\s*\{/g;
  const allNames = new Set();
  let out = src.replace(/^\/\*[\s\S]*?\*\/\n?/, ""); // drop the leading file comment; we'll add our own
  out = out.replace("window.VenomScreens = window.VenomScreens || {};\n", "");

  out = out.replace(re, (whole, dotId, bracketId, fnName, params) => {
    const id = dotId || bracketId;
    const hasGo = /\bgo\b/.test(params);
    registry.push({ id, name: fnName, file: filename });
    return `export function ${fnName}(${hasGo ? "{ go }" : ""}) {`;
  });

  // Remove each function body's `const { ... } = V;` destructure, collecting names.
  out = out.replace(/const\s*\{([^}]+)\}\s*=\s*V;\s*\n?/g, (whole, names) => {
    for (const n of names.split(",").map((s) => s.trim()).filter(Boolean)) allNames.add(n);
    return "";
  });

  const importLine = `import * as React from "react";\nimport { ${[...allNames].sort().join(", ")} } from "../../src/index";\n\n`;
  const header = `// GENERATED by scripts/migrate-screens-to-vite.js from the original ${filename} — hand-edit freely, this is now a real ES module (no longer regenerated automatically).\n`;
  fs.writeFileSync(filePath.replace(/\.jsx$/, ".tsx"), header + importLine + out.trimStart());
  fs.unlinkSync(filePath);
  return filePath.replace(/\.jsx$/, ".tsx");
}

const written = FILES.map(migrateFile);
console.log("Migrated: " + written.map((f) => path.relative(ROOT, f)).join(", "));
console.log("\nScreen registry (id -> component):");
for (const r of registry) console.log(`  ${JSON.stringify(r.id)} -> ${r.name} (${r.file})`);

fs.writeFileSync(
  path.join(DIR, "screen-registry.json"),
  JSON.stringify(registry, null, 2) + "\n"
);
console.log("\nWrote ui_kits/venom-console/screen-registry.json for index.entry.tsx to consume.");
