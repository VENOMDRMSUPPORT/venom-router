#!/usr/bin/env node
// One-time codemod: converts every components/*/*.card.html and states/*.html specimen
// from "3x unpkg CDN script + in-browser Babel JSX" to a real Vite-compiled TSX entry
// module. Mechanical and idempotent — re-running on an already-migrated file is a no-op
// (it detects the absence of the old <script type="text/babel"> block and skips it).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

function findFiles() {
  const out = [];
  for (const dir of fs.readdirSync(path.join(ROOT, "components"))) {
    const full = path.join(ROOT, "components", dir);
    if (!fs.statSync(full).isDirectory()) continue;
    for (const f of fs.readdirSync(full)) {
      if (f.endsWith(".card.html")) out.push(path.join(full, f));
    }
  }
  for (const f of fs.readdirSync(path.join(ROOT, "states"))) {
    if (f.endsWith(".html")) out.push(path.join(ROOT, "states", f));
  }
  return out;
}

function migrate(filePath) {
  const html = fs.readFileSync(filePath, "utf8");
  const babelMatch = html.match(/<script type="text\/babel"[^>]*>([\s\S]*?)<\/script>/);
  if (!babelMatch) return { file: filePath, status: "skipped (already migrated or no babel script)" };

  const inner = babelMatch[1];
  const callMatch = inner.match(/venomMount\(\(\s*V(?:\s*,\s*React)?\s*\)\s*=>\s*\{([\s\S]*)\}\s*\)\s*;\s*$/);
  if (!callMatch) return { file: filePath, status: "SKIPPED — venomMount call shape not recognized", error: true };

  let body = callMatch[1];
  const destructureMatch = body.match(/const\s*\{([^}]+)\}\s*=\s*V;\s*\n?/);
  if (!destructureMatch) return { file: filePath, status: "SKIPPED — no `const { ... } = V;` destructure found", error: true };

  const names = destructureMatch[1]
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);
  body = body.replace(destructureMatch[0], "");

  const isState = filePath.includes(path.sep + "states" + path.sep);
  const relToSrc = isState ? "../src/index" : "../../src/index";

  const entryName = path.basename(filePath).replace(/\.html$/, "").replace(/\.card$/, "");
  const entryFile = path.join(path.dirname(filePath), entryName + ".entry.tsx");

  const tsx = `// GENERATED by scripts/migrate-cards-to-vite.js from ${path.basename(filePath)} — DO NOT EDIT BY HAND.
// Source of truth is the <!-- @dsCard --> markup + this file's sibling .html; re-run the
// codemod (or hand-edit both in lockstep) rather than editing only one side.
import * as React from "react";
import { createRoot } from "react-dom/client";
import { ${names.join(", ")} } from "${relToSrc}";

function Card() {
${body}
}

const rootEl = document.getElementById("root");
if (!rootEl) throw new Error("#root not found");
createRoot(rootEl).render(<Card />);
`;
  fs.writeFileSync(entryFile, tsx);

  // Rewrite the HTML: drop the 3 CDN scripts + card-runtime.js + the babel script,
  // add a single module script pointing at the generated entry.
  let newHtml = html
    .replace(/\s*<script src="https:\/\/unpkg\.com\/react@[^"]*"><\/script>\n?/, "\n")
    .replace(/\s*<script src="https:\/\/unpkg\.com\/react-dom@[^"]*"><\/script>\n?/, "\n")
    .replace(/\s*<script src="[^"]*storybook\/card-runtime\.js"[^>]*><\/script>\n?/, "\n")
    .replace(/\s*<script src="https:\/\/unpkg\.com\/@babel\/standalone@[^"]*"><\/script>\n?/, "\n")
    .replace(/<script type="text\/babel"[^>]*>[\s\S]*?<\/script>/, `<script type="module" src="./${entryName}.entry.tsx"></script>`);

  fs.writeFileSync(filePath, newHtml);
  return { file: filePath, status: "migrated -> " + path.relative(ROOT, entryFile), names };
}

const files = findFiles();
const results = files.map(migrate);
let errors = 0;
for (const r of results) {
  if (r.error) errors++;
  console.log((r.error ? "ERROR " : "OK     ") + path.relative(ROOT, r.file) + " — " + r.status);
}
console.log(`\n${results.length} file(s) processed, ${errors} error(s).`);
if (errors) process.exit(1);
